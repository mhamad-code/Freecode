const dicts: Record<Lang, Dict> = { en: en as unknown as Dict, ar };

interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useLang = create<I18nState>((set) => ({
  lang: ((typeof localStorage !== 'undefined' && localStorage.getItem('fc.lang')) as Lang) || 'en',
  setLang: (lang) => {
    if (typeof localStorage !== 'undefined') localStorage.setItem('fc.lang', lang);
    set({ lang });
  },
}));

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let str = dicts[lang][key] ?? (en as Dict)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.replace(`{${k}}`, String(v));
  return str;
}

export const useI18n = () => {
  const lang = useLang((s) => s.lang);
  const t = (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars);
  return { t, lang, dir: lang === 'ar' ? ('rtl' as const) : ('ltr' as const) };
};
